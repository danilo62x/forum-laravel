    // ─── Tópicos com os campos derivados ────────────────────────────────────

    /** @return array<int,array<string,mixed>> */
    public static function topics(): array
    {
        if (isset(self::$cache['topics'])) {
            return self::$cache['topics'];
        }

        $replies = self::replies();
        $out = [];
        foreach (self::rawTopics() as $raw) {
            $visible = array_values(array_filter(
                $replies,
                fn ($r) => $r['topicId'] === $raw['id'] && ! $r['hidden']
            ));
            $best = null;
            foreach ($visible as $reply) {
                if ($reply['best']) {
                    $best = $reply;
                    break;
                }
            }
            $lastReplyAt = $raw['at'];
            foreach ($visible as $reply) {
                if ($reply['at'] > $lastReplyAt) {
                    $lastReplyAt = $reply['at'];
                }
            }
            $out[] = $raw + [
                'replyCount' => count($visible),
                'lastReplyAt' => $lastReplyAt,
                'bestReplyId' => $best ? $best['id'] : null,
                'solved' => (bool) $best,
            ];
        }

        return self::$cache['topics'] = $out;
    }

