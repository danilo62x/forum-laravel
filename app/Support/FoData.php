    // ─── Imagens (mirror mock.ts imgHash / imgCategory / unsplash) ──────────

    private static function imgHash(string $s): int
    {
        $h = 0;
        $len = mb_strlen($s, 'UTF-8');
        for ($i = 0; $i < $len; $i++) {
            $h = ($h * 31 + mb_ord(mb_substr($s, $i, 1, 'UTF-8'), 'UTF-8')) & 0xFFFFFFFF;
        }

        return $h;
    }

    private static function imgCategory(string $seed): string
    {
        $s = mb_strtolower($seed, 'UTF-8');
        if (preg_match('/author|avatar|member|membro|people|person|profile|staff|team|user/', $s)) {
            return 'people';
        }
        if (preg_match('/city|encontro|hero|urban|cidade/', $s)) {
            return 'city';
        }
        // Capas de categoria alternam entre mesa de trabalho e cidade, sempre pela seed.
        if (preg_match('/capa|categoria|cover/', $s)) {
            return self::imgHash($s) % 3 === 0 ? 'city' : 'work';
        }

        return 'work';
    }

    private static function unsplash(string $id, int $w, int $h): string
    {
        return "https://images.unsplash.com/photo-{$id}?w={$w}&h={$h}&fit=crop&q=70&auto=format";
    }

    /** URL determinística por seed — capas de categoria e imagens de apoio. */
    public static function foImage(string $seed, int $w = 960, int $h = 640): string
    {
        $ids = self::IMG[self::imgCategory($seed)];

        return self::unsplash($ids[self::imgHash('fo-'.$seed) % count($ids)], $w, $h);
    }

    private static function av(string $seed): string
    {
        $ids = self::IMG['people'];

        return self::unsplash($ids[self::imgHash('fo-av-'.$seed) % count($ids)], 160, 160);
    }

    // ─── Datas relativas ────────────────────────────────────────────────────

    private static function daysAgo(int $days, int $hour = 10): string
    {
        $d = new \DateTimeImmutable('now');
        $d = $d->setTime($hour, 0, 0)->modify("-{$days} days");

        return self::iso($d);
    }

    private static function hoursAgo(int $hours): string
    {
        $d = new \DateTimeImmutable('now');
        $d = $d->setTime((int) $d->format('G'), 0, 0)->modify("-{$hours} hours");

        return self::iso($d);
    }

    /** ISO-8601 em UTC com milissegundos, idêntico ao Date#toISOString do JS. */
    private static function iso(\DateTimeImmutable $d): string
    {
        return $d->setTimezone(new \DateTimeZone('UTC'))->format('Y-m-d\TH:i:s.v\Z');
    }

